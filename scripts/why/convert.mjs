// Converts the formations gen.mjs builds (.out/formations.json) into the
// site's generated piece data: components/why/morph/formations/pieces.generated.ts
//
//   node scripts/why/gen.mjs && node scripts/why/convert.mjs
//   (look first: node scripts/why/sketch.mjs F15; node scripts/why/render.mjs --move F15-hands)
//
// Output: POOL (id, kind, clip) and GEOM: one entry per formation id with
//   d: the desktop pieces that changed since the formation before (packed)
//   p: the phone's own pieces (recomposed formations), changed since the
//      formation before when that one was recomposed too, else all of them
//   meta: the storyboard's window, mark, phone placement and move.
// Packed piece: "idx nums...|look" joined by ";". Look codes: role i/s/a/g,
// then optional F<fill i/a/n/g>, W<weight>, B<band>, O<opacity>.
import fs from "node:fs";
import path from "node:path";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const SRC = process.argv[2] ?? path.join(HERE, ".out", "formations.json");
const OUT = process.argv[3] ?? path.resolve(HERE, "../../components/why/morph/formations/pieces.generated.ts");
const j = JSON.parse(fs.readFileSync(SRC, "utf8"));

// Formations in essay order, the via (V13) as its own formation before F13.
const list = [];
for (const f of j.formations) {
  if (f.via) list.push({ ...f.via, id: f.via.id ?? "V13-orb-returns" });
  list.push(f);
}

const pool = j.pool.map((p) => ({ id: p.id, kind: p.kind, clip: !!p.clip }));
const kindOf = Object.fromEntries(pool.map((p) => [p.id, p.kind]));
const idx = Object.fromEntries(pool.map((p, i) => [p.id, i]));

const r1 = (n) => {
  const v = Math.round(n * 10) / 10;
  return Object.is(v, -0) ? 0 : v;
};
const ROLE = { ink: "i", soft: "s", accent: "a", ghost: "g" };
const FILL = { ink: "i", accent: "a", navy: "n", glass: "g" };

function lookCode(p) {
  let c = ROLE[p.stroke ?? "ink"];
  if (!c) throw new Error("role " + p.stroke);
  if (p.fill && p.fill !== "none") c += "F" + FILL[p.fill];
  let weight = p.weight ?? 1;
  let band = 0;
  if (p.sw !== undefined) {
    weight = 0;
    band = p.sw;
  }
  if (weight !== 1) c += "W" + r1(weight);
  if (band) c += "B" + r1(band);
  const o = p.o ?? 1;
  if (o !== 1) c += "O" + Math.round(o * 1000) / 1000;
  if (p.parked) c += "P";
  return c;
}

function nums(kind, p) {
  if (kind === "rect") {
    const a = [p.x, p.y, p.w, p.h, p.r ?? 0];
    if (p.rot) a.push(p.rot);
    return a.map(r1);
  }
  if (kind === "line") return [p.x1, p.y1, p.x2, p.y2].map(r1);
  return [p.cx, p.cy, p.r, p.a0, p.a1].map(r1);
}

const packOne = (id, p) => `${idx[id]} ${nums(kindOf[id], p).join(" ")}|${lookCode(p)}`;

function pack(pieces, prev) {
  const out = [];
  for (const { id } of pool) {
    const p = pieces[id];
    if (!p) continue;
    const s = packOne(id, p);
    if (prev && prev[id] && packOne(id, prev[id]) === s) continue;
    out.push(s);
  }
  return out.join(";");
}

// The crossfades are group fades: the exact mark over the pieces as one
// layer. F13x keeps F13's pieces under it (layer 0 at rest); the pieces
// layer after the pivot comes back as R2-pieces drew them. R2-mark is F13x.
const byId = Object.fromEntries(list.map((f) => [f.id, f]));
const f13 = byId["F13-mark"];
const r2p = byId["R2-pieces"];
let maxShift = 0;
for (const { id } of pool) {
  const a = f13.pieces[id];
  const b = r2p.pieces[id];
  if ((a.o ?? 1) > 0 || (b.o ?? 1) > 0) {
    const d = JSON.stringify(nums(kindOf[id], a)) === JSON.stringify(nums(kindOf[id], b)) && lookCode(a) === lookCode(b) ? 0 : 1;
    if (d) {
      maxShift++;
      console.error("F13 vs R2-pieces differ:", id, packOne(id, a), "->", packOne(id, b));
    }
  }
}
console.error("visible pieces differing between F13 and R2-pieces:", maxShift);

const keep = list.filter((f) => f.id !== "R2-mark");
const geom = {};
let prevD = null;
let prevP = null;
for (const f of keep) {
  let pieces = f.pieces;
  if (f.id === "F13x-exact") pieces = f13.pieces; // the bands stay under the mark; the layer fades
  const d = pack(pieces, prevD);
  prevD = pieces;
  let p;
  if (f.phone?.pieces) {
    p = pack(f.phone.pieces, prevP);
    prevP = f.phone.pieces;
  } else prevP = null;
  const ph = f.phone ?? {};
  const meta = {
    window: f.window,
    mark: f.mark,
    move: f.move,
    phone: { shift: ph.shift, scale: ph.scale, run: ph.run, window: ph.window, own: !!ph.pieces },
  };
  geom[f.id] = { d, ...(p !== undefined ? { p } : {}), ...(f.trace ? { tr: f.trace } : {}), meta };
}

const lines = [];
// (no lint directive: the generated file is plain data)
lines.push("// GENERATED by scripts/why/convert.mjs from the drawings in scripts/why (r1.mjs, r2.mjs; gen.mjs matches the pool).");
lines.push("// Do not edit by hand: formations/essay.ts decodes it and adds the timing.");
lines.push("// Packed piece: \"poolIndex nums|look\"; nums: rect x y w h r [rot], line x1 y1 x2 y2, arc cx cy r a0 a1.");
lines.push("// Look: role i/s/a/g, F<fill i/a/n/g>, W<weight>, B<band>, O<opacity>, P parked. d: desktop pieces changed since the");
lines.push("// formation before; p: the phone's own pieces (recomposed formations), changed since the one before when it");
lines.push("// was recomposed too. tr: the move's traced contours, \"poolIndex i|o start len end\" (formation.ts TraceSpec).");
lines.push(`export const POOL = ${JSON.stringify(pool)} as const;`);
lines.push("export type PackedFormation = { d: string; p?: string; tr?: string; meta: { window?: { x: number; y: number; w: number; h: number; r?: number }; mark?: { cx: number; cy: number; size: number; o?: number; role?: \"ink\" | \"onAccent\" }; move?: { ease?: string; stagger?: number; bend?: number; order?: string | string[] }; phone: { shift?: [number, number]; scale?: number; run?: string; window?: { x: number; y: number; w: number; h: number; r?: number }; own: boolean } } };");
lines.push(`export const GEOM: Record<string, PackedFormation> = ${JSON.stringify(geom)};`);
fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.error("wrote", OUT, fs.statSync(OUT).size, "bytes;", keep.map((f) => f.id).join(" "));
